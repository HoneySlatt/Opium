#!/usr/bin/env python3
"""Writes Icons.kt from the Lucide paths the prototype uses (2 px strokes,
and a few filled glyphs), so the app draws exactly the same icons.

    python3 android/tools/icons.py <opium-mobile.html> > Icons.kt
"""
import re
import sys

html = open(sys.argv[1]).read()


def table(name):
    body = html[html.index(f"const {name} = {{"):]
    body = body[: body.index("\n};")]
    return dict(re.findall(r"(\w+): '([^']*)'", body))


def num(v):
    return float(v)


def to_paths(svg):
    """Every shape of an icon as path data."""
    out = []
    for tag, attrs in re.findall(r"<(path|circle|rect)([^>]*)/?>", svg):
        a = dict(re.findall(r'([\w-]+)="([^"]*)"', attrs))
        if tag == "path":
            out.append(a["d"])
        elif tag == "circle":
            cx, cy, r = num(a["cx"]), num(a["cy"]), num(a["r"])
            out.append(f"M{cx - r} {cy}a{r} {r} 0 1 0 {2 * r} 0a{r} {r} 0 1 0 {-2 * r} 0")
        else:
            x, y = num(a.get("x", 0)), num(a.get("y", 0))
            w, h = num(a["width"]), num(a["height"])
            r = min(num(a.get("rx", 0)), w / 2, h / 2)
            if r == 0:
                out.append(f"M{x} {y}h{w}v{h}h{-w}z")
            else:
                out.append(
                    f"M{x + r} {y}h{w - 2 * r}a{r} {r} 0 0 1 {r} {r}v{h - 2 * r}"
                    f"a{r} {r} 0 0 1 {-r} {r}h{-(w - 2 * r)}a{r} {r} 0 0 1 {-r} {-r}"
                    f"v{-(h - 2 * r)}a{r} {r} 0 0 1 {r} {-r}z"
                )
    return out


def mirrored(svg):
    return "translate(24 0) scale(-1 1)" in svg


def camel(name):
    return name[0].upper() + name[1:]


stroked, filled = table("P"), table("FILLED")
print("// Generated by android/tools/icons.py from the design's Lucide paths.")
print("package io.github.honeyslatt.opium.ui\n")
print("import androidx.compose.ui.graphics.vector.ImageVector\n")
print("object Icons {")
for name, svg in stroked.items():
    paths = ", ".join(f'"{p}"' for p in to_paths(svg))
    print(f"    val {camel(name)}: ImageVector by lazy {{ stroked(\"{name}\", {paths}) }}")
for name, svg in filled.items():
    paths = ", ".join(f'"{p}"' for p in to_paths(svg))
    flip = "true" if mirrored(svg) else "false"
    print(f"    val {camel(name)}: ImageVector by lazy {{ filled(\"{name}\", {flip}, {paths}) }}")
print("}")
